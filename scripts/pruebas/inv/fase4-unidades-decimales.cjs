// FASE 4 — unidades y decimales por producto (opción C mínima). (npm run test:inv)
const L = require('./lib.cjs')
const path = require('path')

;(async () => {
  const antes = L.hashesOrigen()
  const { mod: dbm, dir } = await L.abrir({ etiqueta: 'f4' })
  const seguridad = require(path.join(L.RAIZ, 'electron/seguridad.cjs'))
  const { queryAll, queryOne } = L.helpers(dbm)
  const stock = id => queryOne('SELECT stock FROM productos WHERE id=?', [id]).stock
  const movs = id => queryAll('SELECT * FROM movimientos_stock WHERE producto_id=? ORDER BY id', [id])
  const inv = dbm.inventario

  L.grupo('Migración v5: columnas con valores por defecto')
  const cols = queryAll('PRAGMA table_info(productos)').map(c => c.name)
  L.ok('permite_decimal, decimales, unidad_medida existen', ['permite_decimal', 'decimales', 'unidad_medida'].every(c => cols.includes(c)))
  L.ok('productos previos: permite_decimal=0 (comportamiento actual)', queryOne('SELECT COUNT(*) n FROM productos WHERE COALESCE(permite_decimal,0)<>0').n === 0)
  L.ok('versión de esquema >= 5', dbm.VERSION_ESQUEMA >= 5)

  L.grupo('Producto entero: sigue rechazando decimales')
  const E = inv.create({ nombre: 'F4 Entero', stock: 10, precio_venta: 10 }).id
  let r = inv.ajustarStock({ producto_id: E, tipo: 'entrada', cantidad: 2.5 })
  L.ok('entrada 2.5 en producto entero se rechaza', r.ok === false && /entero/i.test(r.error || ''), JSON.stringify(r))
  L.ok('crear producto entero con stock 1.5 se rechaza', inv.create({ nombre: 'F4 Mal', stock: 1.5 }).ok === false)
  r = inv.venderProductos([{ producto_id: E, nombre_producto: 'x', cantidad: 0.5, precio_unitario: 10 }], {})
  L.ok('vender 0.5 de producto entero se rechaza', r.ok === false)
  L.igual('stock intacto', stock(E), 10)

  L.grupo('Producto en kg con 2 decimales')
  const K = inv.create({ nombre: 'F4 Harina kg', stock: 0, precio_venta: 20, permite_decimal: 1, decimales: 2, unidad_medida: 'kg' }).id
  const pk = queryOne('SELECT * FROM productos WHERE id=?', [K])
  L.ok('se guardó permite_decimal/decimales/unidad_medida', pk.permite_decimal === 1 && pk.decimales === 2 && pk.unidad_medida === 'kg')
  r = inv.ajustarStock({ producto_id: K, tipo: 'entrada', cantidad: 2.5, motivo: 'compra' })
  L.ok('entrada 2,5 kg ok', r.ok === true, JSON.stringify(r))
  L.cerca('stock 2.5', stock(K), 2.5)
  r = inv.ajustarStock({ producto_id: K, tipo: 'entrada', cantidad: 0.1 })
  r = inv.ajustarStock({ producto_id: K, tipo: 'entrada', cantidad: 0.2 })
  L.cerca('2.5 + 0.1 + 0.2 = 2.8 sin deriva', stock(K), 2.8, 1e-12)
  L.ok('se guarda redondeado exacto (no 2.8000000000000003)', stock(K) === 2.8, String(stock(K)))
  r = inv.ajustarStock({ producto_id: K, tipo: 'salida', cantidad: 0.3 })
  L.ok('2.8 − 0.3 = 2.5 exacto', stock(K) === 2.5, String(stock(K)))
  r = inv.ajustarStock({ producto_id: K, tipo: 'entrada', cantidad: 0.123 })
  L.ok('0.123 se redondea a 2 decimales (0.12)', r.ok === true && stock(K) === 2.62, String(stock(K)))
  r = inv.ajustarStock({ producto_id: K, tipo: 'ajuste', cantidad: 7.456 })
  L.ok('ajuste 7.456 → 7.46', r.ok === true && stock(K) === 7.46, String(stock(K)))
  r = inv.ajustarStock({ producto_id: K, tipo: 'salida', cantidad: 10 })
  L.ok('salida mayor al stock se rechaza con decimales también', r.ok === false)
  r = inv.ajustarStock({ producto_id: K, tipo: 'entrada', cantidad: NaN })
  L.ok('NaN se rechaza', r.ok === false)
  r = inv.ajustarStock({ producto_id: K, tipo: 'entrada', cantidad: -1 })
  L.ok('negativa se rechaza', r.ok === false)

  L.grupo('Importación IA: sumar / reemplazar / deshacer sin deriva')
  inv.ajustarStock({ producto_id: K, tipo: 'ajuste', cantidad: 2.5 })
  r = inv.importarLote({ modo: 'sumar', items: [{ accion: 'actualizar', producto_id: K, nombre: 'F4 Harina kg', cantidad: 2.5, unidad: 'kg' }] })
  L.ok('sumar 2.5 kg acepta decimales', r.ok === true, JSON.stringify(r))
  L.ok('stock 5', stock(K) === 5, String(stock(K)))
  const lote1 = r.resultados
  r = inv.deshacerLote({ items: lote1 })
  L.ok('deshacer suma vuelve a 2.5', r.ok === true && stock(K) === 2.5, JSON.stringify(r) + stock(K))
  r = inv.importarLote({ modo: 'reemplazar', items: [{ accion: 'actualizar', producto_id: K, nombre: 'F4 Harina kg', cantidad: 4.75, unidad: 'kg' }] })
  L.ok('reemplazar 4,75', r.ok === true && stock(K) === 4.75, JSON.stringify(r))
  r = inv.deshacerLote({ items: r.resultados })
  L.ok('deshacer reemplazo vuelve a 2.5', r.ok === true && stock(K) === 2.5, JSON.stringify(r))
  // 0.1 + 0.2: la comparación tolerante de deshacerLote no debe fallar por coma flotante
  inv.ajustarStock({ producto_id: K, tipo: 'ajuste', cantidad: 0.1 })
  r = inv.importarLote({ modo: 'sumar', items: [{ accion: 'actualizar', producto_id: K, nombre: 'F4 Harina kg', cantidad: 0.2 }] })
  L.ok('0.1 + 0.2 = 0.3 exacto', r.ok === true && stock(K) === 0.3, String(stock(K)))
  r = inv.deshacerLote({ items: r.resultados })
  L.ok('deshacer 0.1+0.2 ok (comparación tolerante)', r.ok === true && stock(K) === 0.1, JSON.stringify(r) + stock(K))
  inv.ajustarStock({ producto_id: K, tipo: 'ajuste', cantidad: 2.5 })

  L.grupo('Importación IA: reglas de unidad y enteros')
  r = inv.importarLote({ modo: 'sumar', items: [{ accion: 'actualizar', producto_id: K, nombre: 'F4 Harina kg', cantidad: 300, unidad: 'g' }] })
  L.ok('«300 g» en producto kg se rechaza (va a revisión), no se suma 300 kg', r.ok === false && /unidad/i.test(r.error || ''), JSON.stringify(r))
  L.igual('stock intacto tras rechazo', stock(K), 2.5)
  r = inv.importarLote({ modo: 'sumar', items: [{ accion: 'actualizar', producto_id: E, nombre: 'F4 Entero', cantidad: 1.5 }] })
  L.ok('decimal en producto entero se rechaza', r.ok === false)
  r = inv.importarLote({ items: [{ accion: 'crear', nombre: 'F4 Nuevo dec', cantidad: 1.5 }] })
  L.ok('crear nuevo con decimal se rechaza (se crean enteros)', r.ok === false)
  L.igual('stock entero intacto', stock(E), 10)

  L.grupo('Venta fraccionada')
  inv.ajustarStock({ producto_id: K, tipo: 'ajuste', cantidad: 3 })
  r = inv.venderProductos([{ producto_id: K, nombre_producto: 'F4 Harina kg', cantidad: 0.75, precio_unitario: 20 }], { metodo_pago: 'efectivo' })
  L.ok('vender 0.75 kg ok', r.ok === true, JSON.stringify(r))
  L.cerca('total 15.00', r.total, 15)
  L.ok('stock 2.25', stock(K) === 2.25, String(stock(K)))
  const d = queryOne('SELECT cantidad, subtotal FROM detalle_ventas_productos WHERE venta_id=?', [r.venta_id])
  L.ok('detalle guarda 0.75', d.cantidad === 0.75 && d.subtotal === 15, JSON.stringify(d))
  const mv = movs(K).slice(-1)[0]
  L.ok('kardex: venta 0.75, anterior 3, nuevo 2.25, delta −0.75', mv.tipo === 'venta' && mv.cantidad === 0.75 && mv.stock_anterior === 3 && mv.stock_nuevo === 2.25 && Math.abs(mv.delta + 0.75) < 1e-12, JSON.stringify(mv))
  r = inv.venderProductos([{ producto_id: K, nombre_producto: 'x', cantidad: 2.26, precio_unitario: 20 }], {})
  L.ok('vender más de lo que hay (2.26 > 2.25) se rechaza', r.ok === false && stock(K) === 2.25)
  r = inv.venderProductos([{ producto_id: K, nombre_producto: 'x', cantidad: 0.333, precio_unitario: 20 }], {})
  L.ok('0.333 se redondea a 0.33 (total 6.60)', r.ok === true && r.total === 6.6 && stock(K) === 1.92, JSON.stringify(r) + stock(K))

  L.grupo('Anular una venta fraccionada devuelve la fracción')
  r = inv.venderProductos([{ producto_id: K, nombre_producto: 'x', cantidad: 0.5, precio_unitario: 20 }], {})
  const antesAnular = stock(K)
  const det = queryOne('SELECT id FROM detalle_ventas_productos WHERE venta_id=?', [r.venta_id])
  const an = dbm.ventas.anular(r.venta_id, { motivo: 'prueba fase 4', lineas: [{ detalle_id: det.id, vuelve_a_stock: true }], usuario_id: 1, usuario_nombre: 'QA' })
  L.ok('anulación ok', an.ok === true, JSON.stringify(an))
  L.ok('stock vuelve exacto', stock(K) === Math.round((antesAnular + 0.5) * 100) / 100, String(stock(K)))

  L.grupo('Conteo físico con decimales')
  const cont = dbm.conteos.abrir({ producto_ids: [K, E], nota: 'f4' })
  L.ok('abre', cont.ok === true)
  let g = dbm.conteos.registrar(cont.conteo_id, [{ producto_id: K, contado: 1.55 }, { producto_id: E, contado: 9 }])
  L.ok('registrar 1.55 en kg ok', g.ok === true, JSON.stringify(g))
  g = dbm.conteos.registrar(cont.conteo_id, [{ producto_id: E, contado: 8.5 }])
  L.ok('registrar 8.5 en producto entero se rechaza', g.ok === false)
  dbm.conteos.cerrar(cont.conteo_id)
  const ap = dbm.conteos.aprobar(cont.conteo_id, { usuario_id: 1, usuario_nombre: 'QA' })
  L.ok('aprobar ok', ap.ok === true, JSON.stringify(ap))
  L.ok('stock del kg = 1.55 exacto', stock(K) === 1.55, String(stock(K)))
  const rv = dbm.conteos.revertir(cont.conteo_id, { usuario_id: 1, usuario_nombre: 'QA' })
  L.ok('revertir ok', rv.ok === true, JSON.stringify(rv))

  L.grupo('Configuración del producto')
  r = inv.update(K, { nombre: 'F4 Harina kg', precio_venta: 20, permite_decimal: 0, decimales: 0, unidad_medida: 'kg' })
  L.ok('no se puede pasar a entero un producto con stock decimal', r.ok === false || stock(K) === Math.round(stock(K)) , JSON.stringify(r))
  const kk = inv.create({ nombre: 'F4 Litros', stock: 0, precio_venta: 5, permite_decimal: 1, unidad_medida: 'L' }).id
  L.ok('permite_decimal sin decimales usa 2 por defecto', queryOne('SELECT decimales d FROM productos WHERE id=?', [kk]).d === 2)
  r = inv.create({ nombre: 'F4 Raro', stock: 0, permite_decimal: 1, decimales: 9 })
  L.ok('decimales fuera de 0–3 se rechazan', r.ok === false)

  L.grupo('Conciliación con decimales')
  const c = inv.conciliacion().diferencias.filter(x => [K, E].includes(x.producto_id))
  L.igual('kardex de los productos de prueba cuadra', c.length, 0)

  L.grupo('Seguridad: dev_data intacto')
  L.igual('hash de dev_data', L.hashesOrigen(), antes)
  L.limpiar(dir)
  L.fin()
})().catch(e => { console.error(e); process.exit(1) })
