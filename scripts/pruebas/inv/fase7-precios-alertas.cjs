// FASE 7 — historial de precios y alertas de stock. (npm run test:inv)
const L = require('./lib.cjs')
const path = require('path')

;(async () => {
  const antes = L.hashesOrigen()
  const { mod: dbm, dir } = await L.abrir({ etiqueta: 'f7' })
  const seguridad = require(path.join(L.RAIZ, 'electron/seguridad.cjs'))
  const guardas = require(path.join(L.RAIZ, 'electron/guardas.cjs'))({ dbm, seguridad })
  const { queryAll, queryOne } = L.helpers(dbm)
  const inv = dbm.inventario
  for (const [u, rol] of [['qa-admin', 1], ['qa-emp', 2], ['qa-caj', 3]]) dbm.usuarios.create({ username: u, nombre_completo: 'QA ' + u, password: 'qa-pass-1', rol_id: rol })
  const entrar = u => { const r = dbm.usuarios.login(u, 'qa-pass-1'); seguridad.establecer(r.usuario); return r.usuario }
  const adm = entrar('qa-admin')
  const U = { usuario_id: adm.id, usuario_nombre: adm.nombre_completo }
  const hist = (id, campo) => queryAll('SELECT * FROM precios_historial WHERE producto_id=?' + (campo ? ' AND campo=?' : '') + ' ORDER BY id', campo ? [id, campo] : [id])

  L.grupo('Migración v8')
  L.ok('tabla precios_historial', queryAll("SELECT name FROM sqlite_master WHERE type='table'").some(t => t.name === 'precios_historial'))
  L.ok('versión de esquema >= 8', dbm.VERSION_ESQUEMA >= 8)
  L.igual('no se inventa historial para productos existentes', queryOne('SELECT COUNT(*) n FROM precios_historial').n, 0)

  L.grupo('Cambios de precio quedan registrados (solo si cambian)')
  const P = inv.create({ nombre: 'F7 P', stock: 5, precio_venta: 30, precio_compra: 10, ...U }).id
  L.igual('crear no es un «cambio»', hist(P).length, 0)
  const base = { nombre: 'F7 P', precio_venta: 30, precio_compra: 10, ...U }
  inv.update(P, { ...base, descripcion: 'solo descripción' })
  L.igual('editar sin tocar precios: sin filas', hist(P).length, 0)
  inv.update(P, { ...base, precio_venta: 35 })
  let h = hist(P, 'precio_venta')
  L.ok('precio_venta 30 → 35 con usuario y origen', h.length === 1 && h[0].valor_anterior === 30 && h[0].valor_nuevo === 35 && h[0].usuario_id === adm.id && h[0].usuario_nombre === adm.nombre_completo && /edici/i.test(h[0].origen), JSON.stringify(h))
  inv.update(P, { ...base, precio_venta: 35.0 })
  L.igual('mismo valor otra vez: sin fila nueva', hist(P, 'precio_venta').length, 1)
  inv.update(P, { ...base, precio_venta: 35, precio_compra: 12 })
  h = hist(P, 'precio_compra')
  L.ok('precio_compra 10 → 12 registrado', h.length === 1 && h[0].valor_anterior === 10 && h[0].valor_nuevo === 12)
  inv.update(P, { ...base, precio_venta: '35', precio_compra: '12' })
  L.igual('texto «35» equivale a 35: sin filas nuevas', hist(P).length, 2)
  inv.update(P, { ...base, precio_venta: 40, precio_compra: 15, origen: 'prueba' })
  L.igual('dos cambios a la vez → dos filas', hist(P).length, 4)
  L.ok('el origen queda anotado', hist(P, 'precio_venta').slice(-1)[0].origen === 'prueba')
  L.ok('update rechazado no deja historial', (() => { const n = hist(P).length; inv.update(P, { ...base, precio_venta: 99, punto_reorden: -5 }); return hist(P).length === n || queryOne('SELECT precio_venta p FROM productos WHERE id=?', [P]).p === 99 })())

  L.grupo('Costo promedio por compras')
  const Q = inv.create({ nombre: 'F7 Q', stock: 0, precio_venta: 20, ...U }).id
  const c1 = dbm.compras.registrarSimple({ lineas: [{ producto_id: Q, cantidad: 10, costo_unitario: 5 }], ...U })
  L.ok('primera compra: promedio NULL → 5', hist(Q, 'costo_promedio').length === 1 && hist(Q, 'costo_promedio')[0].valor_nuevo === 5 && /Compra #/.test(hist(Q, 'costo_promedio')[0].origen))
  dbm.compras.registrarSimple({ lineas: [{ producto_id: Q, cantidad: 10, costo_unitario: 5 }], ...U })
  L.igual('compra al mismo costo: promedio igual, sin fila', hist(Q, 'costo_promedio').length, 1)
  const c3 = dbm.compras.registrarSimple({ lineas: [{ producto_id: Q, cantidad: 20, costo_unitario: 9 }], ...U })
  L.ok('compra a 9: promedio 5 → 7', hist(Q, 'costo_promedio').length === 2 && hist(Q, 'costo_promedio')[1].valor_anterior === 5 && hist(Q, 'costo_promedio')[1].valor_nuevo === 7)
  dbm.compras.revertirRecepcion(c3.recepcion_id, U)
  const hr = hist(Q, 'costo_promedio')
  L.ok('revertir la compra registra 7 → 5 con su origen', hr.length === 3 && hr[2].valor_anterior === 7 && hr[2].valor_nuevo === 5 && /Reversi/i.test(hr[2].origen), JSON.stringify(hr.slice(-1)))

  L.grupo('Consulta y permisos de costos')
  const g = inv.getHistorialPrecios(P)
  L.ok('historial del producto, el más reciente primero', g.length === 4 && g[0].id > g[g.length - 1].id)
  L.igual('límite', inv.getHistorialPrecios(P, { limite: 2 }).length, 2)
  const r2 = guardas['inventario:getHistorialPrecios'](P)
  L.ok('Admin ve precios y costos', Array.isArray(r2) && r2.some(x => x.campo === 'precio_compra') && r2.some(x => x.campo === 'precio_venta'))
  dbm.getQueryHelpers().run("DELETE FROM rol_permisos WHERE rol_id=2 AND permiso_id=(SELECT id FROM permisos WHERE codigo='inventario.ver_costos')")
  entrar('qa-emp')
  const r3 = guardas['inventario:getHistorialPrecios'](P)
  L.ok('quien no tiene «ver costos» NO ve precio_compra ni costo_promedio', Array.isArray(r3) && r3.length > 0 && r3.every(x => x.campo === 'precio_venta'), JSON.stringify(r3))
  entrar('qa-admin')

  L.grupo('Alertas de stock (comparadas con un conteo propio por SQL)')
  const a = (n, s, extra = {}) => inv.create({ nombre: n, stock: s, precio_venta: 10, stock_minimo: 5, ...extra }).id
  const sin = a('F7 Sin stock', 0), bajo = a('F7 Bajo mínimo', 3), justo = a('F7 Justo en el mínimo', 5), sobrado = a('F7 Sobrado', 50)
  const rep = a('F7 Por reponer', 8); inv.update(rep, { nombre: 'F7 Por reponer', precio_venta: 10, stock_minimo: 5, punto_reorden: 10 })
  const arch = a('F7 Archivado sin stock', 0); inv.archivar(arch, {})
  const elim = a('F7 Eliminado bajo', 1); inv.delete(elim)
  const vivos = "activo=1 AND eliminado=0 AND COALESCE(archivado,0)=0"
  const al = inv.getAlertas()
  L.igual('sin stock = conteo por SQL', al.sin_stock.length, queryOne(`SELECT COUNT(*) n FROM productos WHERE ${vivos} AND stock<=0`).n)
  L.igual('bajo el mínimo = conteo por SQL (stock>0 y ≤ mínimo)', al.bajo_minimo.length, queryOne(`SELECT COUNT(*) n FROM productos WHERE ${vivos} AND stock>0 AND stock<=stock_minimo`).n)
  L.igual('por reponer = conteo por SQL (punto de reorden)', al.a_reponer.length, queryOne(`SELECT COUNT(*) n FROM productos WHERE ${vivos} AND COALESCE(punto_reorden,0)>0 AND stock<=punto_reorden`).n)
  const nombres = l => l.map(x => x.nombre)
  L.ok('«Sin stock» sí; archivado y eliminado no', nombres(al.sin_stock).includes('F7 Sin stock') && !nombres(al.sin_stock).includes('F7 Archivado sin stock') && !nombres([...al.sin_stock, ...al.bajo_minimo]).includes('F7 Eliminado bajo'))
  L.ok('bajo el mínimo incluye «Bajo mínimo» y «Justo en el mínimo», no «Sobrado»', nombres(al.bajo_minimo).includes('F7 Bajo mínimo') && nombres(al.bajo_minimo).includes('F7 Justo en el mínimo') && !nombres(al.bajo_minimo).includes('F7 Sobrado'))
  L.ok('«Por reponer» está en a_reponer (8 ≤ punto 10) aunque sobre el mínimo', nombres(al.a_reponer).includes('F7 Por reponer'))
  L.igual('total = productos distintos con alguna alerta', al.total, queryOne(`SELECT COUNT(*) n FROM productos WHERE ${vivos} AND (stock<=stock_minimo OR (COALESCE(punto_reorden,0)>0 AND stock<=punto_reorden))`).n)
  L.ok('las listas traen nombre, stock y mínimo', al.bajo_minimo.every(x => x.nombre && typeof x.stock === 'number' && x.stock_minimo !== undefined))
  const antesBajo = al.bajo_minimo.length
  inv.ajustarStock({ producto_id: bajo, tipo: 'ajuste', cantidad: 20 })
  L.igual('al reponer, la alerta de ese producto desaparece', inv.getAlertas().bajo_minimo.length, antesBajo - 1)

  L.grupo('Seguridad de las alertas y del historial')
  entrar('qa-caj')
  const tieneVer = seguridad.tiene('inventario.ver')
  const ga = guardas['inventario:getAlertas']()
  L.ok('alertas: respeta inventario.ver', tieneVer ? (ga && ga.ok !== false) : (ga.ok === false && ga.sin_permiso === true), JSON.stringify(ga).slice(0, 80))
  entrar('qa-admin')

  L.grupo('Integridad')
  const tc = JSON.stringify(dbm.respaldosDB.exportarTodo())
  L.ok('precios_historial entra en los respaldos', /precios_historial/.test(tc))
  L.igual('kardex cuadra', inv.conciliacion().diferencias.filter(x => [P, Q].includes(x.producto_id)).length, 0)
  L.igual('hash de dev_data', L.hashesOrigen(), antes)
  L.limpiar(dir)
  L.fin()
})().catch(e => { console.error(e); process.exit(1) })
