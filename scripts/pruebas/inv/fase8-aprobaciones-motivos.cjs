// FASE 8 — aprobación por umbral y motivos de lista fija. (npm run test:inv)
const L = require('./lib.cjs')
const path = require('path')

;(async () => {
  const antes = L.hashesOrigen()
  const { mod: dbm, dir } = await L.abrir({ etiqueta: 'f8' })
  const seguridad = require(path.join(L.RAIZ, 'electron/seguridad.cjs'))
  const guardas = require(path.join(L.RAIZ, 'electron/guardas.cjs'))({ dbm, seguridad })
  const { queryAll, queryOne } = L.helpers(dbm); const run = dbm.getQueryHelpers().run
  const inv = dbm.inventario, AP = dbm.aprobaciones
  const prod = id => queryOne('SELECT * FROM productos WHERE id=?', [id])
  const movs = id => queryAll('SELECT * FROM movimientos_stock WHERE producto_id=? ORDER BY id', [id])
  for (const [u, rol] of [['qa-admin', 1], ['qa-emp', 2], ['qa-caj', 3]]) dbm.usuarios.create({ username: u, nombre_completo: 'QA ' + u, password: 'qa-pass-1', rol_id: rol })
  const entrar = u => { const r = dbm.usuarios.login(u, 'qa-pass-1'); seguridad.establecer(r.usuario); return r.usuario }
  const adm = entrar('qa-admin')
  // El rol 2 puede ajustar stock pero NO aprobar (así es en producción para quien ajusta); se asegura en la copia.
  const pid = c => queryOne('SELECT id FROM permisos WHERE codigo=?', [c]).id
  run('INSERT OR IGNORE INTO rol_permisos (rol_id, permiso_id) VALUES (2, ?)', [pid('inventario.ajustar_stock')])
  run('INSERT OR IGNORE INTO rol_permisos (rol_id, permiso_id) VALUES (2, ?)', [pid('inventario.ver')])
  run('DELETE FROM rol_permisos WHERE rol_id=2 AND permiso_id=?', [pid('inventario.aprobar_ajustes')])
  const emp = () => entrar('qa-emp')
  const ajustar = (d) => guardas['inventario:ajustarStock']({ ...d })
  const P = (n, s) => inv.create({ nombre: n, stock: s, precio_venta: 10 }).id

  L.grupo('Migración v9 y valores por defecto')
  L.ok('tabla aprobaciones', queryAll("SELECT name FROM sqlite_master WHERE type='table'").some(t => t.name === 'aprobaciones'))
  L.ok('movimientos_stock.motivo_codigo', queryAll('PRAGMA table_info(movimientos_stock)').some(c => c.name === 'motivo_codigo'))
  L.ok('versión de esquema >= 9', dbm.VERSION_ESQUEMA >= 9)
  L.igual('la aprobación por umbral viene DESACTIVADA', inv.getUmbralAprobacion(), 0)
  const mot = inv.getMotivos()
  L.ok('lista fija de motivos para salida, ajuste y entrada (con «otro» en salida/ajuste)', ['salida', 'ajuste', 'entrada'].every(t => Array.isArray(mot[t]) && mot[t].length >= 3 && mot[t].every(m => m.codigo && m.etiqueta)) && mot.salida.some(m => m.codigo === 'otro') && mot.ajuste.some(m => m.codigo === 'otro'))

  L.grupo('Motivos obligatorios en salidas y ajustes (canal de la pantalla)')
  const A = P('F8 A', 100)
  let r = ajustar({ producto_id: A, tipo: 'salida', cantidad: 1, motivo: 'sin código' })
  L.ok('salida sin motivo de la lista → rechazada', r.ok === false && /motivo/i.test(r.error || ''), JSON.stringify(r))
  r = ajustar({ producto_id: A, tipo: 'ajuste', cantidad: 90 })
  L.ok('ajuste sin motivo de la lista → rechazado', r.ok === false)
  r = ajustar({ producto_id: A, tipo: 'salida', cantidad: 1, motivo_codigo: 'inventado' })
  L.ok('código que no está en la lista → rechazado', r.ok === false)
  r = ajustar({ producto_id: A, tipo: 'salida', cantidad: 1, motivo_codigo: 'otro', motivo: ' ' })
  L.ok('«otro» sin texto libre → rechazado', r.ok === false)
  L.igual('nada cambió con los rechazos', [prod(A).stock, movs(A).length], [100, 1])
  r = ajustar({ producto_id: A, tipo: 'salida', cantidad: 3, motivo_codigo: 'merma', motivo: 'se cayó la caja' })
  L.ok('salida con «merma» + texto libre ok', r.ok === true, JSON.stringify(r))
  const m1 = movs(A).slice(-1)[0]
  L.ok('se guarda el código Y el texto libre', m1.motivo_codigo === 'merma' && m1.motivo === 'se cayó la caja', JSON.stringify(m1))
  r = ajustar({ producto_id: A, tipo: 'ajuste', cantidad: 95, motivo_codigo: 'conteo_fisico' })
  L.ok('ajuste con motivo de la lista ok (texto libre opcional)', r.ok === true && prod(A).stock === 95)
  r = ajustar({ producto_id: A, tipo: 'entrada', cantidad: 5 })
  L.ok('entrada: el motivo de la lista no es obligatorio', r.ok === true && prod(A).stock === 100)
  r = dbm.inventario.ajustarStock({ producto_id: A, tipo: 'salida', cantidad: 1 })
  L.ok('llamadas internas del sistema (sin canal) conservan su comportamiento', r.ok === true && prod(A).stock === 99)

  L.grupo('Sin umbral configurado: todo se aplica directo')
  r = ajustar({ producto_id: A, tipo: 'ajuste', cantidad: 5, motivo_codigo: 'correccion_error' })
  L.ok('ajuste enorme se aplica (la función viene desactivada)', r.ok === true && !r.pendiente_aprobacion && prod(A).stock === 5)
  ajustar({ producto_id: A, tipo: 'ajuste', cantidad: 100, motivo_codigo: 'correccion_error' })

  L.grupo('Configurar el umbral')
  emp()
  const bad = guardas['inventario:setUmbralAprobacion'](10)
  L.ok('quien no administra no puede cambiarlo', bad.ok === false && bad.sin_permiso === true, JSON.stringify(bad))
  entrar('qa-admin')
  L.ok('valor negativo rechazado', guardas['inventario:setUmbralAprobacion'](-3).ok === false)
  L.ok('valor no numérico rechazado', guardas['inventario:setUmbralAprobacion']('abc').ok === false)
  L.ok('umbral 10 ok y auditado', guardas['inventario:setUmbralAprobacion'](10).ok === true && inv.getUmbralAprobacion() === 10 && queryAll("SELECT id FROM auditoria WHERE accion='UMBRAL_APROBACION'").length >= 1)

  L.grupo('Con umbral 10: quien ajusta sin poder aprobar queda pendiente')
  const B = P('F8 B', 100)
  emp()
  r = ajustar({ producto_id: B, tipo: 'salida', cantidad: 12, motivo_codigo: 'vencimiento' })
  L.ok('salida de 12 (≥10) queda PENDIENTE', r.ok === true && r.pendiente_aprobacion === true && r.aprobacion_id > 0, JSON.stringify(r))
  const ap1 = r.aprobacion_id
  L.igual('el stock NO cambió y no hay movimiento', [prod(B).stock, movs(B).length], [100, 1])
  r = ajustar({ producto_id: B, tipo: 'salida', cantidad: 9, motivo_codigo: 'vencimiento' })
  L.ok('salida de 9 (<10) se aplica directo', r.ok === true && !r.pendiente_aprobacion && prod(B).stock === 91)
  r = ajustar({ producto_id: B, tipo: 'ajuste', cantidad: 50, motivo_codigo: 'conteo_fisico' })
  L.ok('ajuste de 91 → 50 (diferencia 41) queda pendiente', r.ok === true && r.pendiente_aprobacion === true)
  const ap2 = r.aprobacion_id
  r = ajustar({ producto_id: B, tipo: 'entrada', cantidad: 500 })
  L.ok('una ENTRADA grande no pide aprobación', r.ok === true && !r.pendiente_aprobacion && prod(B).stock === 591)
  r = ajustar({ producto_id: B, tipo: 'salida', cantidad: 9999, motivo_codigo: 'merma' })
  L.ok('lo imposible se rechaza de entrada (no se encola)', r.ok === false && !/pendiente/i.test(r.error || '') && AP.contarPendientes() === 2, JSON.stringify(r))
  const verPropias = guardas['aprobaciones:getAll']({ estado: 'pendiente' })
  L.ok('el solicitante ve sus solicitudes, con producto, cantidad y motivo', Array.isArray(verPropias) && verPropias.length === 2 && verPropias.every(x => x.solicitado_por_nombre && x.producto_nombre))
  const apr = guardas['aprobaciones:aprobar'](ap1)
  L.ok('quien ajusta NO puede aprobar su propia solicitud', apr.ok === false && apr.sin_permiso === true)
  L.ok('…y la solicitud sigue pendiente', queryOne('SELECT estado FROM aprobaciones WHERE id=?', [ap1]).estado === 'pendiente')

  L.grupo('Quien puede aprobar: sus propios ajustes no se frenan, y aprueba/rechaza los ajenos')
  entrar('qa-admin')
  const C = P('F8 C', 100)
  r = ajustar({ producto_id: C, tipo: 'salida', cantidad: 50, motivo_codigo: 'robo_perdida' })
  L.ok('el aprobador ajusta directo (queda auditado)', r.ok === true && !r.pendiente_aprobacion && prod(C).stock === 50)
  const todas = guardas['aprobaciones:getAll']({ estado: 'pendiente' })
  L.ok('el aprobador ve TODAS las pendientes', todas.length === 2)
  const stockB0 = prod(B).stock
  r = guardas['aprobaciones:aprobar'](ap1)
  L.ok('aprobar la salida de 12 la aplica', r.ok === true && prod(B).stock === stockB0 - 12, JSON.stringify(r))
  const mA = movs(B).slice(-1)[0]
  L.ok('el movimiento queda a nombre de quien lo pidió, con código, y dice quién aprobó', mA.tipo === 'salida' && mA.cantidad === 12 && mA.motivo_codigo === 'vencimiento' && /aprobad/i.test(mA.motivo || '') && mA.usuario_nombre !== adm.nombre_completo, JSON.stringify(mA))
  const fila = queryOne('SELECT * FROM aprobaciones WHERE id=?', [ap1])
  L.ok('estado aprobada con quién y cuándo', fila.estado === 'aprobada' && fila.resuelto_por === adm.id && !!fila.fecha_resolucion)
  L.ok('no se puede aprobar dos veces', guardas['aprobaciones:aprobar'](ap1).ok === false)
  L.ok('rechazar exige un motivo', guardas['aprobaciones:rechazar'](ap2, { nota: ' ' }).ok === false && queryOne('SELECT estado FROM aprobaciones WHERE id=?', [ap2]).estado === 'pendiente')
  const stockB1 = prod(B).stock
  r = guardas['aprobaciones:rechazar'](ap2, { nota: 'no coincide con el conteo' })
  L.ok('rechazar no toca el stock', r.ok === true && prod(B).stock === stockB1 && queryOne('SELECT estado, nota_resolucion FROM aprobaciones WHERE id=?', [ap2]).nota_resolucion === 'no coincide con el conteo')
  L.ok('lo rechazado no se puede aprobar después', guardas['aprobaciones:aprobar'](ap2).ok === false && prod(B).stock === stockB1)
  L.igual('ya no hay pendientes', AP.contarPendientes(), 0)

  L.grupo('Aprobar cuando el stock cambió: se revalida')
  emp()
  const D = P('F8 D', 30)
  r = ajustar({ producto_id: D, tipo: 'salida', cantidad: 25, motivo_codigo: 'merma' })
  const ap3 = r.aprobacion_id
  inv.ajustarStock({ producto_id: D, tipo: 'salida', cantidad: 20 })     // mientras tanto bajó a 10
  entrar('qa-admin')
  r = guardas['aprobaciones:aprobar'](ap3)
  L.ok('ya no alcanza el stock → error claro y NADA se aplica', r.ok === false && /stock/i.test(r.error || '') && prod(D).stock === 10, JSON.stringify(r))
  L.ok('…y la solicitud sigue pendiente (se puede rechazar)', queryOne('SELECT estado FROM aprobaciones WHERE id=?', [ap3]).estado === 'pendiente')
  guardas['aprobaciones:rechazar'](ap3, { nota: 'ya no hay stock' })

  L.grupo('Desactivar el umbral')
  L.ok('umbral 0 lo desactiva', guardas['inventario:setUmbralAprobacion'](0).ok === true && inv.getUmbralAprobacion() === 0)
  emp()
  r = ajustar({ producto_id: C, tipo: 'ajuste', cantidad: 1, motivo_codigo: 'correccion_error' })
  L.ok('con el umbral desactivado, todo directo otra vez', r.ok === true && !r.pendiente_aprobacion && prod(C).stock === 1)
  entrar('qa-admin')

  L.grupo('Auditoría e integridad')
  const aud = queryAll("SELECT accion FROM auditoria WHERE accion IN ('SOLICITAR_APROBACION_AJUSTE','APROBAR_AJUSTE','RECHAZAR_AJUSTE')").map(x => x.accion)
  L.ok('auditoría de solicitud, aprobación y rechazo', ['SOLICITAR_APROBACION_AJUSTE', 'APROBAR_AJUSTE', 'RECHAZAR_AJUSTE'].every(a => aud.includes(a)), aud.join(','))
  L.igual('kardex cuadra', inv.conciliacion().diferencias.filter(x => [A, B, C, D].includes(x.producto_id)).length, 0)
  L.ok('aprobaciones entra en los respaldos', /aprobaciones/.test(JSON.stringify(dbm.respaldosDB.exportarTodo())))
  L.igual('hash de dev_data', L.hashesOrigen(), antes)
  L.limpiar(dir)
  L.fin()
})().catch(e => { console.error(e); process.exit(1) })
