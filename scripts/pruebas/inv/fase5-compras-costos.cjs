// FASE 5 — compras y costo (promedio ponderado). (npm run test:inv)
const L = require('./lib.cjs')
const path = require('path')

;(async () => {
  const antes = L.hashesOrigen()
  const { mod: dbm, dir } = await L.abrir({ etiqueta: 'f5' })
  const seguridad = require(path.join(L.RAIZ, 'electron/seguridad.cjs'))
  const guardas = require(path.join(L.RAIZ, 'electron/guardas.cjs'))({ dbm, seguridad })
  const { queryAll, queryOne, run } = L.helpers(dbm)
  const inv = dbm.inventario, C = dbm.compras
  const prod = id => queryOne('SELECT * FROM productos WHERE id=?', [id])
  const movs = id => queryAll('SELECT * FROM movimientos_stock WHERE producto_id=? ORDER BY id', [id])
  for (const [u, rol] of [['qa-admin', 1], ['qa-emp', 2], ['qa-caj', 3]]) dbm.usuarios.create({ username: u, nombre_completo: 'QA ' + u, password: 'qa-pass-1', rol_id: rol })
  const entrar = u => { const r = dbm.usuarios.login(u, 'qa-pass-1'); seguridad.establecer(r.usuario); return r.usuario }
  const adm = entrar('qa-admin')
  const U = { usuario_id: adm.id, usuario_nombre: adm.nombre_completo }
  const P = (n, s = 0, extra = {}) => inv.create({ nombre: n, stock: s, precio_venta: 30, ...extra }).id

  L.grupo('Migración v6: esquema y datos previos')
  const tablas = queryAll("SELECT name FROM sqlite_master WHERE type='table'").map(t => t.name)
  L.ok('tablas de compras', ['ordenes_compra', 'orden_compra_lineas', 'recepciones_compra', 'recepcion_lineas'].every(t => tablas.includes(t)))
  const cp = queryAll('PRAGMA table_info(productos)').map(c => c.name)
  L.ok('columnas de producto', ['costo_promedio', 'ultimo_costo', 'punto_reorden', 'cantidad_reorden'].every(c => cp.includes(c)))
  L.ok('movimientos_stock.costo_unitario y detalle.costo_unitario', queryAll('PRAGMA table_info(movimientos_stock)').some(c => c.name === 'costo_unitario') && queryAll('PRAGMA table_info(detalle_ventas_productos)').some(c => c.name === 'costo_unitario'))
  L.ok('versión de esquema >= 6', dbm.VERSION_ESQUEMA >= 6)
  const sinCostoAntiguas = queryOne('SELECT COUNT(*) n FROM detalle_ventas_productos WHERE costo_unitario IS NOT NULL').n
  L.igual('ventas antiguas: «sin costo registrado» (NULL), nada inventado', sinCostoAntiguas, 0)
  const conPC = queryOne('SELECT COUNT(*) n FROM productos WHERE precio_compra>0').n
  L.igual('costo_promedio inicial = precio_compra donde hay precio', queryOne('SELECT COUNT(*) n FROM productos WHERE precio_compra>0 AND costo_promedio=precio_compra AND ultimo_costo=precio_compra').n, conPC)
  L.igual('sin precio_compra → costo desconocido (NULL)', queryOne('SELECT COUNT(*) n FROM productos WHERE COALESCE(precio_compra,0)=0 AND costo_promedio IS NOT NULL').n, 0)

  L.grupo('Compra simple: promedio ponderado')
  const X = P('F5 X')
  let r = C.registrarSimple({ lineas: [{ producto_id: X, cantidad: 10, costo_unitario: 5 }], nota: 'compra 1', ...U })
  L.ok('compra 10 @ 5 ok', r.ok === true, JSON.stringify(r))
  L.ok('stock 10, promedio 5, último 5', prod(X).stock === 10 && prod(X).costo_promedio === 5 && prod(X).ultimo_costo === 5)
  const rec1 = r.recepcion_id
  r = C.registrarSimple({ lineas: [{ producto_id: X, cantidad: 10, costo_unitario: 7 }], ...U })
  L.ok('compra 10 @ 7 ok', r.ok === true)
  L.ok('promedio = 6, último = 7, stock 20', prod(X).costo_promedio === 6 && prod(X).ultimo_costo === 7 && prod(X).stock === 20, JSON.stringify(prod(X)))
  const rec2 = r.recepcion_id
  const mc = movs(X).filter(m => m.tipo === 'entrada')
  L.ok('kardex guarda costo_unitario de cada entrada (5 y 7)', mc.length === 2 && mc[0].costo_unitario === 5 && mc[1].costo_unitario === 7, JSON.stringify(mc))
  L.ok('la compra queda como orden recibida (modo simple)', queryOne("SELECT estado, tipo FROM ordenes_compra WHERE id=?", [r.orden_id]).estado === 'recibida')

  L.grupo('La venta congela el costo del momento')
  const v = inv.venderProductos([{ producto_id: X, nombre_producto: 'F5 X', cantidad: 2, precio_unitario: 30 }], { metodo_pago: 'efectivo', ...U })
  L.ok('venta ok', v.ok === true, JSON.stringify(v))
  L.cerca('detalle.costo_unitario = 6', queryOne('SELECT costo_unitario c FROM detalle_ventas_productos WHERE venta_id=?', [v.venta_id]).c, 6)
  r = C.registrarSimple({ lineas: [{ producto_id: X, cantidad: 10, costo_unitario: 20 }], ...U })
  L.cerca('compras posteriores NO cambian el costo ya congelado', queryOne('SELECT costo_unitario c FROM detalle_ventas_productos WHERE venta_id=?', [v.venta_id]).c, 6)
  const x2 = prod(X)
  L.ok('stock 28 y promedio (18·6+10·20)/28 = 11', x2.stock === 28 && Math.abs(x2.costo_promedio - 11) < 1e-9, JSON.stringify(x2))
  L.ok('mov. de venta lleva costo 6', movs(X).find(m => m.tipo === 'venta').costo_unitario === 6)
  // Deshacer con stock cambiado (hubo una venta antes de la última compra: la última recepción sí está intacta)
  const ult = r.recepcion_id
  r = C.revertirRecepcion(ult, U)
  L.ok('revertir la ÚLTIMA compra (stock sin cambios después) ok', r.ok === true, JSON.stringify(r))
  L.ok('promedio vuelve a 6 y último a 7, stock 18', Math.abs(prod(X).costo_promedio - 6) < 1e-9 && prod(X).ultimo_costo === 7 && prod(X).stock === 18, JSON.stringify(prod(X)))
  L.ok('se hizo con movimiento INVERSO (la entrada original sigue)', movs(X).filter(m => m.tipo === 'entrada').length === 3 && movs(X).slice(-1)[0].tipo === 'salida' && movs(X).slice(-1)[0].cantidad === 10)
  L.ok('revertir dos veces se rechaza', C.revertirRecepcion(ult, U).ok === false)
  r = C.revertirRecepcion(rec2, U)
  L.ok('revertir una compra anterior con ventas posteriores se rechaza (stock cambió)', r.ok === false && /cambi|venta|stock/i.test(r.error || ''), JSON.stringify(r))
  L.ok('…y no toca nada', prod(X).stock === 18 && Math.abs(prod(X).costo_promedio - 6) < 1e-9)

  L.grupo('Escenario del enunciado: 10@5 + 10@7 → 6; deshacer la última → 5')
  const Y = P('F5 Y')
  C.registrarSimple({ lineas: [{ producto_id: Y, cantidad: 10, costo_unitario: 5 }], ...U })
  const ry = C.registrarSimple({ lineas: [{ producto_id: Y, cantidad: 10, costo_unitario: 7 }], ...U })
  L.cerca('promedio 6', prod(Y).costo_promedio, 6)
  C.revertirRecepcion(ry.recepcion_id, U)
  L.ok('tras deshacer: promedio 5, último 5, stock 10', prod(Y).costo_promedio === 5 && prod(Y).ultimo_costo === 5 && prod(Y).stock === 10, JSON.stringify(prod(Y)))

  L.grupo('Orden de compra: borrador → enviada → parcial → recibida')
  const A = P('F5 A'), B = P('F5 B')
  const prov = queryOne('SELECT id FROM proveedores LIMIT 1')?.id
  r = C.crear({ proveedor_id: prov || null, nota: 'pedido', lineas: [{ producto_id: A, cantidad: 10, costo_unitario: 4 }, { producto_id: B, cantidad: 6, costo_unitario: 9 }], ...U })
  L.ok('crea en borrador', r.ok === true && C.getById(r.orden_id).estado === 'borrador', JSON.stringify(r))
  const oid = r.orden_id
  L.ok('no se puede recibir un borrador', C.recibir(oid, { lineas: [] }, U).ok === false)
  L.ok('enviar', C.enviar(oid, U).ok === true && C.getById(oid).estado === 'enviada')
  const ord = C.getById(oid)
  const la = ord.lineas.find(l => l.producto_id === A), lb = ord.lineas.find(l => l.producto_id === B)
  r = C.recibir(oid, { lineas: [{ linea_id: la.id, cantidad: 4 }] }, U)
  L.ok('recepción parcial 4 de 10', r.ok === true && C.getById(oid).estado === 'recibida_parcial' && prod(A).stock === 4, JSON.stringify(r))
  L.cerca('costo de la línea (4) aplicado: promedio 4', prod(A).costo_promedio, 4)
  const recP = r.recepcion_id
  L.ok('no se puede recibir más de lo pendiente (7 > 6)', C.recibir(oid, { lineas: [{ linea_id: la.id, cantidad: 7 }] }, U).ok === false && prod(A).stock === 4)
  L.ok('no se puede cancelar con mercadería ya recibida', C.cancelar(oid, { motivo: 'x', ...U }).ok === false)
  r = C.recibir(oid, { lineas: [{ linea_id: la.id, cantidad: 6, costo_unitario: 5 }, { linea_id: lb.id, cantidad: 6 }] }, U)
  L.ok('resto con costo distinto (5) → recibida', r.ok === true && C.getById(oid).estado === 'recibida', JSON.stringify(r))
  L.ok('A: stock 10, promedio (4·4+6·5)/10 = 4.6', prod(A).stock === 10 && Math.abs(prod(A).costo_promedio - 4.6) < 1e-9, JSON.stringify(prod(A)))
  const rr = C.revertirRecepcion(r.recepcion_id, U)
  L.ok('revertir la última recepción: orden vuelve a parcial', rr.ok === true && C.getById(oid).estado === 'recibida_parcial', JSON.stringify(rr))
  L.ok('A: stock 4, promedio 4; B: stock 0', prod(A).stock === 4 && prod(A).costo_promedio === 4 && prod(B).stock === 0)
  L.ok('cantidad_recibida de las líneas se recalcula', C.getById(oid).lineas.find(l => l.producto_id === A).cantidad_recibida === 4)
  L.ok('cancelar orden en borrador', (() => { const o = C.crear({ lineas: [{ producto_id: A, cantidad: 1, costo_unitario: 1 }], ...U }); return C.cancelar(o.orden_id, { motivo: 'ya no hace falta', ...U }).ok === true && C.getById(o.orden_id).estado === 'cancelada' })())
  L.ok('cancelar dos veces se rechaza', (() => { const o = C.crear({ lineas: [{ producto_id: A, cantidad: 1, costo_unitario: 1 }], ...U }); C.cancelar(o.orden_id, { motivo: 'abc', ...U }); return C.cancelar(o.orden_id, { motivo: 'abc', ...U }).ok === false })())

  L.grupo('Validaciones y todo-o-nada')
  const Z = P('F5 Z', 3)
  for (const [n, linea] of [['cantidad 0', { cantidad: 0, costo_unitario: 1 }], ['cantidad negativa', { cantidad: -2, costo_unitario: 1 }], ['costo negativo', { cantidad: 1, costo_unitario: -1 }], ['costo NaN', { cantidad: 1, costo_unitario: NaN }], ['cantidad decimal en producto entero', { cantidad: 1.5, costo_unitario: 1 }]]) {
    L.ok(`rechaza ${n}`, C.registrarSimple({ lineas: [{ producto_id: Z, ...linea }], ...U }).ok === false)
  }
  L.ok('rechaza sin líneas', C.registrarSimple({ lineas: [], ...U }).ok === false)
  L.ok('rechaza producto inexistente', C.registrarSimple({ lineas: [{ producto_id: 999999, cantidad: 1, costo_unitario: 1 }], ...U }).ok === false)
  L.ok('rechaza proveedor inexistente', C.registrarSimple({ proveedor_id: 999999, lineas: [{ producto_id: Z, cantidad: 1, costo_unitario: 1 }], ...U }).ok === false)
  const W = P('F5 W'); inv.archivar(W, U)
  L.ok('rechaza producto archivado', C.registrarSimple({ lineas: [{ producto_id: W, cantidad: 1, costo_unitario: 1 }], ...U }).ok === false)
  r = C.registrarSimple({ lineas: [{ producto_id: Z, cantidad: 5, costo_unitario: 2 }, { producto_id: W, cantidad: 1, costo_unitario: 1 }], ...U })
  L.ok('una línea mala ⇒ no se aplica NADA (stock de la buena intacto)', r.ok === false && prod(Z).stock === 3 && queryOne('SELECT COUNT(*) n FROM ordenes_compra WHERE nota IS NULL AND estado=\'recibida\' AND id>(SELECT MAX(id)-1 FROM ordenes_compra)').n >= 0)
  L.igual('…y sin movimientos nuevos', movs(Z).length, 1)

  L.grupo('Stock previo sin costo conocido')
  const S = P('F5 S', 10)
  L.ok('arranca sin costo (NULL)', prod(S).costo_promedio === null)
  C.registrarSimple({ lineas: [{ producto_id: S, cantidad: 10, costo_unitario: 8 }], ...U })
  L.ok('promedio = 8 (no se inventa costo para el stock previo)', prod(S).costo_promedio === 8 && prod(S).stock === 20)

  L.grupo('Productos con decimales')
  const K = P('F5 kg', 0, { permite_decimal: 1, decimales: 2, unidad_medida: 'kg' })
  C.registrarSimple({ lineas: [{ producto_id: K, cantidad: 2.5, costo_unitario: 10 }], ...U })
  C.registrarSimple({ lineas: [{ producto_id: K, cantidad: 1.25, costo_unitario: 16 }], ...U })
  L.ok('stock 3.75 y promedio 12', prod(K).stock === 3.75 && Math.abs(prod(K).costo_promedio - 12) < 1e-9, JSON.stringify(prod(K)))

  L.grupo('IA «sumar» sin costo no promedia')
  const antesProm = prod(X).costo_promedio
  r = inv.importarLote({ modo: 'sumar', items: [{ accion: 'actualizar', producto_id: X, nombre: 'F5 X', cantidad: 5 }], ...U })
  L.ok('sumar ok', r.ok === true)
  L.ok('promedio intacto y movimiento sin costo', prod(X).costo_promedio === antesProm && movs(X).slice(-1)[0].costo_unitario === null)
  inv.deshacerLote({ items: r.resultados, ...U })
  L.ok('deshacer la suma deja el promedio igual', prod(X).costo_promedio === antesProm)

  L.grupo('Reposición sugerida por punto de reorden')
  const R1 = P('F5 R1', 3), R2 = P('F5 R2', 20), R3 = P('F5 R3', 1), R4 = P('F5 R4', 0)
  inv.update(R1, { nombre: 'F5 R1', precio_venta: 30, punto_reorden: 5, cantidad_reorden: 12 })
  inv.update(R2, { nombre: 'F5 R2', precio_venta: 30, punto_reorden: 5 })
  inv.update(R3, { nombre: 'F5 R3', precio_venta: 30, punto_reorden: 4 })
  inv.update(R4, { nombre: 'F5 R4', precio_venta: 30 })
  L.ok('update guarda punto_reorden y cantidad_reorden', prod(R1).punto_reorden === 5 && prod(R1).cantidad_reorden === 12)
  const sug = C.sugerirReposicion().filter(s => [R1, R2, R3, R4].includes(s.producto_id))
  L.igual('solo bajo el punto de reorden (R1 y R3)', sug.map(s => s.producto_id).sort(), [R1, R3].sort())
  L.ok('cantidad sugerida: la configurada (12) o la que falta (4−1=3)… ≥1', sug.find(s => s.producto_id === R1).sugerido === 12 && sug.find(s => s.producto_id === R3).sugerido >= 1)
  inv.archivar(R3, U)
  L.ok('archivados no se sugieren', !C.sugerirReposicion().some(s => s.producto_id === R3))

  L.grupo('Seguridad: permisos, usuario de la sesión y auditoría')
  const permComp = queryOne("SELECT id FROM permisos WHERE codigo='inventario.compras'")
  L.ok('permiso inventario.compras existe', !!permComp)
  const rolesComp = queryAll('SELECT rol_id FROM rol_permisos WHERE permiso_id=?', [permComp.id]).map(x => x.rol_id).sort()
  const rolesAj = queryAll("SELECT rp.rol_id FROM rol_permisos rp JOIN permisos p ON p.id=rp.permiso_id WHERE p.codigo='inventario.ajustar_stock'").map(x => x.rol_id)
  L.igual('lo tienen Admin y quien ya podía ajustar stock (nadie gana ni pierde acceso)', rolesComp, [...new Set([1, ...rolesAj])].sort())
  const sinPermiso = [2, 3].find(rol => !rolesComp.includes(rol))
  if (sinPermiso) {
    entrar(sinPermiso === 2 ? 'qa-emp' : 'qa-caj')
    const d = guardas['compras:registrarSimple']({ lineas: [{ producto_id: X, cantidad: 1, costo_unitario: 1 }] })
    L.ok('rol sin permiso → rechazado por el proceso principal', d.ok === false && d.sin_permiso === true, JSON.stringify(d))
    entrar('qa-admin')
  } else L.ok('(todos los roles tienen permiso: nada que rechazar)', true)
  const g = guardas['compras:registrarSimple']({ lineas: [{ producto_id: X, cantidad: 1, costo_unitario: 6 }], usuario_id: 999, usuario_nombre: 'Impostor' })
  L.ok('compra por el canal protegido ok', g.ok === true, JSON.stringify(g))
  const rc = queryOne('SELECT usuario_id, usuario_nombre FROM recepciones_compra WHERE id=?', [g.recepcion_id])
  L.ok('el usuario es el de la sesión, no el que manda la pantalla', rc.usuario_id === adm.id && rc.usuario_nombre !== 'Impostor', JSON.stringify(rc))
  const aud = queryAll("SELECT accion FROM auditoria WHERE accion IN ('RECIBIR_COMPRA','REVERTIR_RECEPCION','CREAR_ORDEN_COMPRA','CANCELAR_ORDEN_COMPRA')").map(a => a.accion)
  L.ok('auditoría de recepción, reversión, creación y cancelación', ['RECIBIR_COMPRA', 'REVERTIR_RECEPCION', 'CREAR_ORDEN_COMPRA', 'CANCELAR_ORDEN_COMPRA'].every(a => aud.includes(a)), aud.join(','))

  L.grupo('Integridad al final')
  const ids = [X, Y, A, B, Z, S, K]
  L.igual('kardex cuadra con el stock en todos los productos de la prueba', inv.conciliacion().diferencias.filter(d => ids.includes(d.producto_id)).length, 0)
  const tc = dbm.respaldosDB && dbm.respaldosDB.exportarTodo ? JSON.stringify(dbm.respaldosDB.exportarTodo()) : ''
  L.ok('las tablas de compras entran en los respaldos', /ordenes_compra/.test(tc) && /recepciones_compra/.test(tc))
  L.igual('hash de dev_data', L.hashesOrigen(), antes)
  L.limpiar(dir)
  L.fin()
})().catch(e => { console.error(e); process.exit(1) })
